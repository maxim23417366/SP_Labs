/**
  ******************************************************************************
  * @file    uart_rx.h
  * @brief   ЛР3: прийом USART2 через DMA у кільцевий буфер (внутрішнє для Platform/).
  *
  *          Чому не опитування і не переривання RXNE:
  *            - опитування з task_uart() губило байти (ORE), коли цикл стояв довше
  *              2 символів (~174 мкс): security ~1,6 мс, env/DHT11 ~41 мс, printf;
  *            - RXNE-переривання не рятує вікна з __disable_irq(): зчитування DHT11
  *              (~5 мс, platform_io.c) і лінія кадру OV7670 (camera_dvp.c) — за 5 мс
  *              приходить ~57 байтів, а приймач тримає лише 1.
  *          DMA1 Stream5 / Channel 4 (USART2_RX, RM0383 табл. 27) пише байти в пам'ять
  *          апаратно, незалежно від PRIMASK і зайнятості циклу. Програма лише читає
  *          буфер: UartRx_Get().
  *
  *          Переповнення кільця (цикл не читав > UART_RX_BUF байтів, ~178 мс при
  *          115200) не мовчазне: UartRx_Get() один раз повертає PLATFORM_UART_LOST
  *          на місці втрати, і cmd.c відкидає зіпсований рядок цілком.
  ******************************************************************************
  */
#ifndef UART_RX_H
#define UART_RX_H

#include <stdint.h>

/* Розмір кільця, степінь двійки. 2048 Б = 178 мс прийому на 115200 8N1: з запасом
 * більше за найдовше блокування циклу (повний STATS ~0,2 с — лише якщо ПК весь цей
 * час безперервно шле). Половина (1024 Б, 89 мс) — межа запізнення переривання
 * DMA HT/TC, яку не перевищує жодне вікно __disable_irq() (найдовше ~5 мс). */
#define UART_RX_BUF   2048U

void     UartRx_Start(void);          /* налаштувати DMA і почати прийом */
int      UartRx_Get(void);            /* байт 0..255, PLATFORM_UART_NONE або PLATFORM_UART_LOST */
uint32_t UartRx_Lost(void);           /* скільки разів кільце переповнилось */
uint32_t UartRx_Peak(void);           /* найбільше неприйняте програмою, Б */

#endif /* UART_RX_H */
