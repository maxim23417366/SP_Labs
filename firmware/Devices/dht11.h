/**
  ******************************************************************************
  * @file    dht11.h
  * @brief   DHT11: розбір 40-бітної відповіді датчика температури й вологості.
  *
  *          Сам обмін по лінії DATA (18 мс LOW від МК, далі 40 біт, де ширина
  *          HIGH кодує біт: ~26–28 мкс = 0, ~70 мкс = 1) робить Platform/,
  *          бо він залежить від таймінгів МК. Тут лише перевірка і перетворення
  *          п'яти байт, тому драйвер виконується і на платі, і в тестах на ПК.
  ******************************************************************************
  */
#ifndef DHT11_H
#define DHT11_H

#include <stdint.h>

#include "dev_bus.h"

#define DHT11_FRAME_LEN  5U

typedef struct
{
  uint8_t rh_pct;      /* відносна вологість, % (ціла частина) */
  uint8_t rh_tenth;    /* десяті частки % RH (байт 1; у більшості DHT11 = 0..9) */
  int8_t  temp_c;      /* температура, °C (DHT11 дає 0..50) */
  uint8_t temp_tenth;  /* десяті частки °C (у більшості DHT11 = 0..9) */
} dht11_data_t;

/* Збирає 40 тривалостей HIGH (мкс) у 5 байт: тривалість > threshold_us → 1. */
void dht11_bits_to_bytes(const uint16_t high_us[40], uint16_t threshold_us,
                         uint8_t frame[DHT11_FRAME_LEN]);

/* Перевіряє контрольну суму (байт 4 = сума байтів 0..3 mod 256) і діапазони.
 * DEV_ERR_STATE — сума не збіглась, DEV_ERR_ID — значення поза паспортними. */
dev_status_t dht11_decode(const uint8_t frame[DHT11_FRAME_LEN], dht11_data_t *out);

#endif /* DHT11_H */
