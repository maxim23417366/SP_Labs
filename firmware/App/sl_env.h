/**
  ******************************************************************************
  * @file    sl_env.h
  * @brief   ЛР3 (K06, Коваль): DHT11 і BMP180 — FR-14, FR-15.
  *
  *          Модуль реалізує сильну SmartLock_EnvPoll() (smartlock_hooks.h) і
  *          замінює слабку зі smartlock_hooks_weak.c. Викликається раз на
  *          TBD_PERIOD_ENV_US. Подія до FSM одна:
  *
  *            SL_EV_ENV_WARNING  ТРИВАЛИЙ вихід температури / вологості DHT11
  *                               за межі (FR-14). arg — бітова маска
  *                               SL_ENV_WARN_*: що саме вийшло за межі.
  *                               FSM журналює її в будь-якому стані і стан не
  *                               змінює.
  *
  *          Модуль не постить жодних інших подій. BMP180 — лише тиск у UART
  *          (FR-15): без подій, без тривог, без окремої температури.
  *          Несправність DHT11 / BMP180 не створює подій LOCK / UNLOCK і
  *          сама по собі не дає ENV_WARNING.
  *
  *          Рядок UART (формат збережено з слабкого хука, байт у байт):
  *            ENV,dht=ok,t_c=21.1,rh=41,bmp=ok,p_pa=100349\r\n
  *            ENV,dht=err,bmp=err\r\n          (t_c/rh — лише при dht=ok,
  *                                              p_pa — лише при bmp=ok)
  *
  *          Правила ENV_WARNING (ухвалені рішення K06; числа — TBD_, див. нижче):
  *
  *          1. Вихід за межу — СТРОГО за межею (T > TBD_ENV_T_MAX_C тощо).
  *             Показник на самій межі ще «в нормі».
  *          2. Гістерезис: показник, що вийшов за межу, вважається нормою лише
  *             коли повернувся ВГЛИБ допустимої зони на величину гістерезису
  *             (T <= max - TBD_ENV_T_HYST_C, RH <= max - TBD_ENV_RH_HYST_PCT;
  *             аналогічно для нижніх меж). Усередині смуги гістерезису стан
  *             попереднього зразка зберігається — відлік не скидається і
  *             повторної події не буде. Показник, що коливається на межі, не
  *             дає серії подій.
  *          3. Відлік тривалості — окремо для T і для RH, за now_ms
  *             (беззнакова різниця uint32_t, стійка до переповнення). Параметр
  *             «дозрів», коли поза межами безперервно >= TBD_ENV_WARN_DURATION_MS.
  *          4. Подія кладеться, щойно з'явився дозрілий параметр, якого ще не
  *             оголошували. arg = маска ВСІХ зараз дозрілих параметрів.
  *             Повторна подія для параметра — лише після його повернення в
  *             норму (з гістерезисом) і нового тривалого перевищення.
  *          5. Зміна маски під час активної тривоги: якщо T уже оголошено, а
  *             RH дозрів пізніше — кладеться ЩЕ ОДНА подія з повною маскою
  *             (T|RH), щоб журнал показав новий склад. Якщо параметр повернувся
  *             в норму, а інший лишається — подія не кладеться (зменшення
  *             складу не нова тривога), але параметр знімається з «оголошених»,
  *             тож його нове тривале перевищення дасть нову подію. Параметр, що
  *             ще не дозрів, у маску не входить.
  *          6. Відмова DHT11 (тайм-аут, контрольна сума, поза паспортом): зразок
  *             не є ні «в межах», ні «поза межами». Короткі серії відмов
  *             (< TBD_ENV_DHT_ERR_RESET_COUNT поспіль) стан НЕ змінюють: час
  *             перевищення тече за годинником, бо DHT11 нерідко дає поодинокі
  *             помилки контрольної суми, і скидання відліку на кожній з них
  *             назавжди відкладало б тривогу. Події під час відмови не
  *             кладуться (немає свіжих даних) — вона з'явиться з першим
  *             валідним зразком. Тривала серія (>= TBD_ENV_DHT_ERR_RESET_COUNT
  *             поспіль) означає, що даних немає: весь відлік і «оголошені»
  *             скидаються, і після відновлення датчика перевищення починається
  *             з нуля (при тривалому збої можливе повторне оголошення того
  *             самого перевищення — прийнятно для необов'язкового датчика).
  *          7. Якщо SmartLock_PostEvent() повернула false (черга повна), параметр
  *             лишається «неоголошеним» і спроба повторюється при наступному
  *             виклику; лічильник SmartLock_EnvPostFailed().
  *
  *          Блокувальні виклики: DHT11 ~25 мс і BMP180 ~12 мс (logs/13) —
  *          задокументовані блокувальні місця ЛР3, які вимірюються; модуль
  *          нових очікувань не додає.
  ******************************************************************************
  */
#ifndef SL_ENV_H
#define SL_ENV_H

#include <stdbool.h>
#include <stdint.h>

/* ---- маска arg події SL_EV_ENV_WARNING (визначає K06, не вимога PRD) --------- */
#define SL_ENV_WARN_T    (1UL << 0)   /* температура DHT11 поза межами */
#define SL_ENV_WARN_RH   (1UL << 1)   /* відносна вологість DHT11 поза межами */

/* ---- TBD_: PRD (FR-14) чисел не задає -------------------------------------------
 * Значення ТИМЧАСОВІ, не вимога; у звіт вони не йдуть як вимоги. Межі лежать у
 * паспортному діапазоні DHT11 (datasheet: 0–50 °C, 20–90 %RH, точність
 * ±2 °C / ±5 %RH), решта — тимчасове, погодити з Сюкало (L01, матриця FR-14). */
#define TBD_ENV_T_MIN_C              5      /* °C; нижче — ENV_WARNING (тимчасове) */
#define TBD_ENV_T_MAX_C              40     /* °C; вище — ENV_WARNING (тимчасове) */
#define TBD_ENV_RH_MIN_PCT           20     /* %RH; нижче — тимчасове (нижня межа паспорта DHT11) */
#define TBD_ENV_RH_MAX_PCT           80     /* %RH; вище — тимчасове (паспорт дозволяє до 90) */
#define TBD_ENV_WARN_DURATION_MS     60000U /* безперервний вихід до події; тимчасове (30 зразків при 2 с) */
#define TBD_ENV_T_HYST_C             1      /* °C гістерезису; тимчасове (паспортна точність ±2 °C) */
#define TBD_ENV_RH_HYST_PCT          3      /* %RH гістерезису; тимчасове (паспортна точність ±5 %) */
#define TBD_ENV_DHT_ERR_RESET_COUNT  5U     /* відмов DHT11 поспіль до скидання відліку; тимчасове */

/* Скидання внутрішнього стану модуля (тести). Нульовий стан і є початковим,
 * тож на платі окрема ініціалізація не потрібна. */
void SmartLock_EnvInit(void);

/* ---- геттери для діагностики / STATS ------------------------------------------ */

/* Останні ВАЛІДНІ T (у 0,1 °C) і RH (%) DHT11; false — валідних ще не було.
 * Відмова останні значення не стирає. Будь-який з покажчиків може бути NULL. */
bool SmartLock_EnvLastDht(int16_t *t_dc, uint8_t *rh_pct);

/* Останній валідний тиск BMP180, Па; false — валідних ще не було. */
bool SmartLock_EnvLastPressure(int32_t *p_pa);

uint32_t SmartLock_EnvDhtErrors(void);       /* усього відмов DHT11 */
uint32_t SmartLock_EnvDhtErrStreak(void);    /* відмов DHT11 поспіль зараз */
uint32_t SmartLock_EnvBmpErrors(void);       /* відмов BMP180 (включно з baro_status != OK) */
uint32_t SmartLock_EnvWarningsPosted(void);  /* успішно покладених ENV_WARNING */
uint32_t SmartLock_EnvPostFailed(void);      /* PostEvent повернула false (черга повна) */
uint32_t SmartLock_EnvActiveMask(void);      /* параметри, про які вже оголошено ENV_WARNING */

#endif /* SL_ENV_H */
