/**
  ******************************************************************************
  * @file    bench.h
  * @brief   Стенд ЛР2: команди з UART для перевірки кожного пристрою і
  *          відтворюваних записів логічним аналізатором.
  *          Перевірки — stand_test.c, формат ST-рядків — self_test.c.
  *
  *          Формат рядків придатний для автоматичного розбору:
  *            ST,<пристрій>,<OK|WARN|FAIL|SKIP>,ключ=значення,... — self-test
  *            <ТЕМА>,ключ=значення,...                         — вивід команд
  *            # ...                                            — коментар
  ******************************************************************************
  */
#ifndef BENCH_H
#define BENCH_H

/* Повний self-test (StandTest_Run) і довідка з командами */
void Bench_SelfTest(void);

/* Довідка з командами */
void Bench_Help(void);

/* Обробка одного символу з UART і стеження за входами (режим ЛР2) */
void Bench_Poll(void);

/* ЛР3: одна однолітерна команда ЛР2 (s, i, g, m, b, h, j, f, 1/2/3, a, c, k, x, l, ?).
 * Діагностичні команди блокують цикл (h — ~8 с, m — ~1 с): у сценаріях S1–S3 їх
 * не використовують (docs/tasks.md §2). */
void Bench_Command(int c);

/* ЛР3: друк стабільної зміни входів, якщо увімкнено командою g */
void Bench_Watch(void);

#endif /* BENCH_H */
