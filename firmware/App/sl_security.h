/**
  ******************************************************************************
  * @file    sl_security.h
  * @brief   ЛР3 (K05, Коваль): PIR, MPU-6050, геркон — FR-05, FR-06, FR-13.
  *
  *          Модуль реалізує сильну SmartLock_SecurityPoll() (smartlock_hooks.h)
  *          замість слабкої зі smartlock_hooks_weak.c. FSM напряму не
  *          викликається — лише події в черзі (event_queue.h):
  *
  *            SL_EV_MOTION       PIR: рух (FR-05). arg = 0.
  *            SL_EV_TAMPER       MPU-6050: удар / вібрація понад поріг (FR-06).
  *                               arg = НА СКІЛЬКИ метрика перевищила поріг, мg
  *                               (метрика − TBD_TAMPER_THRESHOLD_MG, завжди ≥ 1).
  *            SL_EV_DOOR_OPEN    геркон: стабільно відчинено (FR-13). arg = 0.
  *            SL_EV_DOOR_CLOSED  геркон: стабільно зачинено (FR-13). arg = 0.
  *
  *          Модуль не знає стану FSM: MOTION / TAMPER постяться в будь-якому
  *          стані, FSM реагує лише в LOCKED. DOOR_* — лише при зміні стабільного
  *          (після антидребезгу) стану і ОДИН раз після старту — початковий
  *          стан: до першої DOOR_* FSM вважає двері відчиненими і не блокує.
  *          Короткі нестабільні переходи не дають DOOR_* (PRD, «Уточнення
  *          поведінки»), бо DOOR_OPEN у LOCKED = FORCED_OPEN.
  *
  *          Входи: Platform_ReadInputs(): PLATFORM_IN_DOOR — 0 = магніт поруч
  *          (зачинено), 1 = відчинено (docs/pinout.md, logs/04); PLATFORM_IN_PIR —
  *          1 = рух. MPU-6050 — app_devices.mpu (app.h), mpu6050_read_raw().
  *          pir_edge / mpu_edge у хуку — фронти з EXTI (підключає I04; до того
  *          false): модуль працює за рівнями, а pir_edge лише додатково
  *          вважається фронтом і проходить через ту саму перевірку мінімального
  *          інтервалу, тож фронт + рівень в одному проході дають одну подію.
  *          mpu_edge не потрібен: датчик і так читається в кожному виклику
  *          (INT у самому MPU не ввімкнено — docs/lab_3/driver-audit.md).
  *
  *          Відмови MPU-6050 (логи 08, 10, 15) не впливають на геркон і PIR:
  *            - mpu_status != DEV_OK            — датчик не читається;
  *            - помилка I2C                     — лічильник, без події; після
  *                                                TBD_MPU_ERR_LIMIT поспіль
  *                                                датчик несправний, а читання
  *                                                рідшають (шина, що висить,
  *                                                блокує ~26 мс на звернення);
  *            - усі осі точно 0 (модуль після втрати живлення відповідає без
  *              помилки, лог 08/15) TBD_MPU_ZERO_LIMIT поспіль — несправний.
  *          При відновленні базова лінія збирається заново, стрибок «0 → 1 g»
  *          не дає TAMPER.
  *
  *          Усі TBD_ нижче — НЕ затверджені PRD. Значення виведені з логів
  *          стенда; реальних ударів у логах немає, тож поріг TAMPER потрібно
  *          підтвердити на стенді (Колодницький: серія контрольованих впливів і
  *          легких дотиків, FR-06) і погодити з Сюкало (L01).
  ******************************************************************************
  */
#ifndef SL_SECURITY_H
#define SL_SECURITY_H

#include <stdbool.h>
#include <stdint.h>

/* ---- TBD_ значення -------------------------------------------------------------- */

/* Антидребезг геркона, мс: новий рівень має триматися не менше цього часу.
 * Джерело: logs/03, 04 — найкоротший навмисний стан «магніт поруч» 624 мс
 * (рука з магнітом), тож 100 мс його не губить; опитування раз на 20 мс
 * (TBD_PERIOD_SECURITY_US) дає ≥ 5 послідовних однакових зразків. Дребезг
 * контактів самого геркона в логах не видно (стенд 20 мс фільтрував), вібрація
 * дверей — оцінка. Підтвердити осцилографом. */
#ifndef TBD_DOOR_DEBOUNCE_MS
#define TBD_DOOR_DEBOUNCE_MS        100U
#endif

/* Мінімальний інтервал між подіями MOTION, мс. Джерело: logs/03, 04 — HC-SR501
 * на одну присутність дає серію імпульсів по ~1 с із проміжками між фронтами
 * 3,1–6,5 с; 8 с об'єднує сусідні імпульси серії. Довша присутність дає подію
 * раз на 8 с (кожна — запис журналу і кадр камери). Побічний ефект: імпульс у
 * межах 8 с після події, яку FSM відкинула поза LOCKED, теж гаситься. */
#ifndef TBD_PIR_MIN_INTERVAL_MS
#define TBD_PIR_MIN_INTERVAL_MS     8000U
#endif

/* Поріг TAMPER, мg: сума |Δ| трьох осей між сусідніми зразками (див. sl_security.c).
 * Джерело: logs/09 (92 виміри, спокій 104 с), 11 (44 виміри, спокій), 08 —
 * найбільша сума |Δ| у спокої 32 мg (шум по осях 13–25 мg розмахом). Поворот
 * макета руками (лог 11, зразки раз на 1,1 с) інтерпольований до кроку 20 мс
 * дає до ~35 мg на крок. 200 мg — ~6 × шуму і ~5 × повільного повороту.
 * УДАРІВ У ЛОГАХ НЕМАЄ: значення — інженерна оцінка, межі діапазону ±2 g. */
#ifndef TBD_TAMPER_THRESHOLD_MG
#define TBD_TAMPER_THRESHOLD_MG     200U
#endif

/* Мінімальний інтервал між подіями TAMPER, мс: один удар дає кілька зразків
 * над порогом (затухання), а запис журналу і кадр камери — по одному на подію.
 * Оцінка, логів із ударами немає. */
#ifndef TBD_TAMPER_MIN_INTERVAL_MS
#define TBD_TAMPER_MIN_INTERVAL_MS  1000U
#endif

/* Зразків на встановлення базової лінії після старту і після відновлення MPU
 * (події не формуються): 5 × 20 мс = 100 мс. Джерело: logs/09 — шум стабільний
 * від першого виміру, довгого прогріву не видно; оцінка. */
#ifndef TBD_MPU_BASELINE_SAMPLES
#define TBD_MPU_BASELINE_SAMPLES    5U
#endif

/* Зразків поспіль з усіма нульовими осями, після яких MPU несправний. Джерело:
 * logs/08 (6 вимірів 0,000 після втрати живлення), logs/15 розд. 3. */
#ifndef TBD_MPU_ZERO_LIMIT
#define TBD_MPU_ZERO_LIMIT          3U
#endif

/* Помилок читання I2C поспіль, після яких MPU несправний. Джерело: logs/10
 * (130 із 130 err=bus), logs/15 розд. 1: поодинока помилка не повинна гасити
 * охорону, серія — повинна. */
#ifndef TBD_MPU_ERR_LIMIT
#define TBD_MPU_ERR_LIMIT           3U
#endif

/* Пауза між спробами читання, поки MPU несправний через помилки I2C, мс.
 * Джерело: logs/15 розд. 1 — звернення до зависшої шини триває ~26 мс, а
 * без паузи це 130 % часу циклу при періоді 20 мс. */
#ifndef TBD_MPU_RETRY_MS
#define TBD_MPU_RETRY_MS            1000U
#endif

/* ---- Інтерфейс ------------------------------------------------------------------ */

/* Скидання внутрішнього стану модуля (тести; на платі стан після старту вже
 * нульовий, окремої ініціалізації не потрібно). */
void SmartLock_SecurityInit(void);

/* ---- Діагностика (UART STATS / тести) ------------------------------------------- */

/* MPU придатний до роботи: mpu_status == DEV_OK, серії помилок I2C і нульових
 * зразків немає. До першого читання — true, якщо mpu_status == DEV_OK. */
bool     SlSecurity_MpuHealthy(void);
uint32_t SlSecurity_MpuErrors(void);        /* усього помилок читання I2C */
uint32_t SlSecurity_MpuZeroSamples(void);   /* усього зразків з нульовими осями */

/* MOTION / TAMPER, які SmartLock_PostEvent() відкинула (черга повна) */
uint32_t SlSecurity_EventsLost(void);

/* Невдалих спроб покласти DOOR_* в чергу (подію повторено в наступному виклику) */
uint32_t SlSecurity_DoorRetries(void);

#endif /* SL_SECURITY_H */
