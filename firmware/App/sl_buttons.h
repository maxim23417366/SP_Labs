/**
  ******************************************************************************
  * @file    sl_buttons.h
  * @brief   ЛР3 (K03/K04, Коваль): USER B1 і код з 4 кнопок — FR-02, FR-09, FR-10.
  *
  *          Модуль реалізує сильну SmartLock_ButtonsPoll() (smartlock_hooks.h),
  *          яка заміщує слабку зі smartlock_hooks_weak.c. FSM напряму не
  *          викликається — лише події в черзі (event_queue.h):
  *
  *            SL_EV_LOCK_REQUEST  прийняте (після антидребезгу) натискання B1.
  *                                arg = now_ms моменту прийняття (збігається з
  *                                Platform_Millis() у виклику задачі) — від нього
  *                                FSM рахує 15 с (FR-03). Якщо в цей мілісекундний
  *                                момент now_ms == 0, arg збігається з
  *                                SL_LOCK_REQ_T_NOW, і FSM рахує від моменту, коли
  *                                забере подію (різниця — один прохід циклу).
  *            SL_EV_CODE_OK       введено правильну послідовність (FR-10).
  *            SL_EV_CODE_WRONG    неправильну послідовність (FR-10).
  *                                arg для CODE_* — кількість введених символів
  *                                (діагностика; сам код у подію / журнал не йде).
  *
  *          Модуль не знає стану FSM: CODE_* і LOCK_REQUEST постяться завжди,
  *          FSM ігнорує їх там, де вони не мають сенсу (CODE_* поза LOCKED,
  *          LOCK_REQUEST поза UNLOCKED — E2E-01: повторний B1 не перезапускає
  *          відлік).
  *
  *          Входи: Platform_ReadInputs(), біти PLATFORM_IN_BTN1..4 і
  *          PLATFORM_IN_LOCK (B1), натиснуто = 0 (pull-up, docs/pinout.md).
  *
  *          Антидребезг (усі 5 кнопок): новий рівень стає «стабільним», коли
  *          утримується TBD_BTN_DEBOUNCE_MS за now_ms (різниця uint32 — стійка до
  *          переповнення). Подія — один раз на стабільне натискання, без
  *          автоповтору при утриманні, відпускання подій не дає. Кнопка, затиснута
  *          на момент першого опитування, не дає події до відпускання.
  *
  *          b1_edge (фронт з EXTI, підключає I04; зараз завжди false) НЕ постить
  *          подію сам: це лише підказка «рівень B1 міг змінитись», яка
  *          перезапускає відлік антидребезгу B1. Подія все одно виникає тільки
  *          зі стабільного рівня, тому фронт + рівень не дають подвійного
  *          LOCK_REQUEST, а одиночний фронт без стабільного рівня (завада) не дає
  *          жодного.
  *
  *          Введення коду: кнопки BTN1..BTN4 дають символи 1..4. Після
  *          TBD_CODE_LEN символів порівнюється з TBD_CODE_VALUE і постяться
  *          CODE_OK / CODE_WRONG, введення скидається. Пауза між прийнятими
  *          натисканнями >= TBD_CODE_TIMEOUT_MS скидає незавершене введення
  *          (без події). Одночасне натискання двох і більше кнопок коду
  *          (прийняті в одному опитуванні) — неоднозначний акорд: усі символи
  *          акорду відкидаються, введення і відлік паузи не змінюються. B1 з
  *          кодом не пов'язана і обробляється незалежно.
  *
  *          Повернення SmartLock_ButtonsPoll(): true лише якщо була корисна
  *          робота — змінився стабільний стан кнопки, поставлено подію або
  *          скинуто введення за тайм-аутом. Порожнє опитування (false) не має
  *          потрапляти в CPU Load.
  *
  *          Натискання під час довгих операцій (issue #51): опитування не бачить
  *          натискання, яке почалося й закінчилося, поки цикл стояв (зйомка й запис
  *          кадру — до ~2,9 с). Платформа ловить кнопки коду ще й через EXTI і віддає
  *          завершені натискання з часом (Platform_TakeKey). Ті, яких опитування не
  *          прийняло, стають символами коду з часом натискання; повтори того, що
  *          опитування вже прийняло, і акорди відкидаються. Порядок символів і
  *          тайм-аут — за часом натискань, а не за часом обробки.
  *
  *          Повна черга: PostEvent повернув false — подію не втрачаємо мовчки,
  *          лічильник SmartLock_ButtonsDropped().
  *
  *          Параметри нижче — TBD_: у PRD їх немає, це не вимоги.
  ******************************************************************************
  */
#ifndef SL_BUTTONS_H
#define SL_BUTTONS_H

#include <stdint.h>

/* TBD: час стабільного рівня для антидребезгу, мс. Джерело: стенд ЛР2, команда g
 * (docs/lab_3/logs/03_*.txt, 04_*.txt — «антидребезг 20 мс»). Власного виміру
 * дребезгу немає: docs/captures/gpio_button_bounce.sr (1 МГц) містить одне чисте
 * натискання ~130 мс без жодного відскоку — значення НЕ підтверджене
 * вимірюванням. Тимчасове, погодити з Сюкало (L01). */
#define TBD_BTN_DEBOUNCE_MS     20U

/* TBD: довжина коду, символів (1..255). Тимчасове, погодити з Сюкало (L01);
 * PRD (FR-09) задає лише «чотири зовнішні кнопки». */
#define TBD_CODE_LEN            4U

/* TBD: значення коду — символи 1..4 (номер кнопки BTN1..BTN4), рівно
 * TBD_CODE_LEN елементів. Тимчасове, погодити з Сюкало (L01). Зберігається в
 * const-масиві sl_buttons.c; у події / журнал / UART не потрапляє. */
#define TBD_CODE_VALUE          { 1U, 3U, 2U, 4U }

/* TBD: макс. пауза між прийнятими натисканнями коду, мс; далі введення
 * скидається. Тимчасове, погодити з Сюкало (L01); у PRD цього немає. */
#define TBD_CODE_TIMEOUT_MS     5000U

/* Скидання внутрішнього стану модуля (тести; на платі — лінива ініціалізація
 * при першому SmartLock_ButtonsPoll(): запам'ятовує вихідні рівні кнопок). */
void SmartLock_ButtonsInit(void);

/* Скільки подій PostEvent відкинув (черга повна) з моменту ButtonsInit() */
uint32_t SmartLock_ButtonsDropped(void);

/* Скільки символів коду введено в незавершеній послідовності (діагностика) */
unsigned SmartLock_ButtonsCodeProgress(void);

/* issue #51: скільки натискань коду додала EXTI-черга платформи (Platform_TakeKey) —
 * ті, що почалися й закінчилися, поки цикл стояв (зйомка, запис кадру), і яких
 * опитування не побачило. Див. «Натискання під час довгих операцій» вище. */
uint32_t SmartLock_ButtonsLate(void);

#endif /* SL_BUTTONS_H */
