/**
  ******************************************************************************
  * @file    cmd.h
  * @brief   ЛР3 (I03): рядкові команди UART поверх однолітерних команд стенда ЛР2.
  *
  *          Рядок, що починається з ВЕЛИКОЇ латинської літери, накопичується до
  *          '\r' або '\n' і виконується цілком. Усе інше (малі літери, цифри, '?')
  *          іде в Bench_Command() — команди self-test ЛР2 працюють як раніше.
  *
  *            STATS | STATS RAW | STATS RESET   — метрики Super Loop (stats.h)
  *            MEM                               — стек і heap
  *            PING <n>                          — відповідь PONG (потік команд, §6.2.3)
  *            MARK <n>                          — мітка сценарію в EVT-лозі (I04)
  *            HELP
  ******************************************************************************
  */
#ifndef CMD_H
#define CMD_H

#include <stdint.h>

/* 1 — символ належить рядковій команді (поглинуто), 0 — передати в Bench_Command() */
int      Cmd_Feed(int c);

/* Виконати готовий рядок (без '\r\n') */
void     Cmd_Execute(const char *line);

void     Cmd_Reset(void);
uint32_t Cmd_LineOverflows(void);

#endif /* CMD_H */
